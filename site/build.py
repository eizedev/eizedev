"""Build the eize.dev landing page and the projects part of README.md from projects.toml.

    uv run site/build.py                 # page into _site/ (reads icons, screenshots, versions online)
    uv run site/build.py --readme        # rewrite the projects part of README.md (offline)
    uv run site/build.py --check-readme  # exit 1 when README.md does not match projects.toml

The page is plain HTML with inline CSS and SVG and no JavaScript; its Content-Security-Policy
allows only images from the site itself and the one inline stylesheet (by hash).
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import html
import io
import json
import re
import shutil
import sys
import tomllib
import urllib.error
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SITE = Path(__file__).resolve().parent
README = ROOT / "README.md"
README_START = "<!-- projects:start - generated by site/build.py from projects.toml, edit that file instead -->"
README_END = "<!-- projects:end -->"
SHIELDS = "https://img.shields.io"
USER_AGENT = "eize.dev-site-build"
# Widths of the pivotkit screenshot on the page (the source is 1440 px wide).
SHOT_WIDTHS = (720, 1440)
# Files of the eizedev logo kit in eizedev/brand that the page serves from its root.
BRAND_FILES = {
    "favicon.ico": "eizedev/favicon/favicon.ico",
    "favicon.svg": "eizedev/favicon/favicon.svg",
    "apple-touch-icon.png": "eizedev/favicon/apple-touch-icon.png",
    "icon-192.png": "eizedev/favicon/icon-192.png",
    "icon-512.png": "eizedev/favicon/icon-512.png",
    "site.webmanifest": "eizedev/favicon/site.webmanifest",
    "social-preview.png": "eizedev/png/social-preview-1280x640.png",
}
REGISTRIES = {"pypi": "PyPI", "npm": "npm", "powershellgallery": "PowerShell Gallery"}
# README badge colours (One Dark), as in the rest of the profile.
BADGE_STYLE = "style=flat-square&labelColor=1f2430"
BLUE, GREEN = "61afef", "98c379"

esc = html.escape


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=20) as response:
        return response.read()


def shields_json_url(badge: str) -> str:
    path, _, query = badge.partition("?")
    return f"{SHIELDS}/{path}.json" + (f"?{query}" if query else "")


def shields_value(badge: str) -> str | None:
    """The value a shields.io badge shows ("v0.3.0", "367"), or None when it cannot be read.

    A missing version must not stop the page from being built, so failures only warn."""
    try:
        message = json.loads(fetch(shields_json_url(badge)))["message"]
    except (urllib.error.URLError, TimeoutError, KeyError, ValueError) as error:
        print(f"warning: no value for {badge}: {error}", file=sys.stderr)
        return None
    if message in ("invalid", "not found", "inaccessible", "no releases or repo not found"):
        print(f"warning: no value for {badge}: {message}", file=sys.stderr)
        return None
    return message.removeprefix("v")


def badge_image(badge: str, colour: str, label: str | None = None) -> str:
    path, _, query = badge.partition("?")
    params = "&".join(p for p in (query, BADGE_STYLE, f"color={colour}", f"label={label}" if label else "") if p)
    return f"{SHIELDS}/{path}?{params}"


def badge_link(badge: str) -> str:
    """Where a badge leads: the package page of its registry, or the releases of a repository."""
    path = badge.partition("?")[0]
    kind, _, rest = path.partition("/")
    if kind == "pypi":
        return f"https://pypi.org/project/{rest.split('/')[-1]}/"
    if kind == "npm":
        return f"https://www.npmjs.com/package/{rest.split('/')[-1]}"
    if kind == "powershellgallery":
        return f"https://www.powershellgallery.com/packages/{rest.split('/')[-1]}"
    if kind == "github":
        owner, repo = rest.split("/")[2:4]
        return f"https://github.com/{owner}/{repo}/releases"
    raise ValueError(f"no link for badge {badge}")


def registry_name(badge: str) -> str:
    return REGISTRIES.get(badge.split("/", 1)[0], "")


def github_url(repo: str) -> str:
    return f"https://github.com/{repo}"


def inline_svg(svg: str, css_class: str) -> str:
    """An SVG from eizedev/brand as decoration inside the page."""
    svg = re.sub(r"<\?xml[^>]*>\s*", "", svg).strip()
    return svg.replace("<svg ", f'<svg class="{css_class}" aria-hidden="true" focusable="false" ', 1)


# ---------------------------------------------------------------------------------------- page


class Page:
    def __init__(self, config: dict, out: Path):
        self.config = config
        self.out = out
        self.brand = config["site"]["brand"]

    def brand_svg(self, path: str, css_class: str = "") -> str:
        return inline_svg(fetch(f"{self.brand}/{path}").decode(), css_class)

    def icon(self, project: dict) -> str:
        if "icon" in project:
            return self.brand_svg(project["icon"])
        return f'<span class="glyph" aria-hidden="true">{esc(project["glyph"])}</span>'

    def screenshot(self, shot: dict, link: str) -> str:
        """The pivotkit screenshot as WebP in two widths, light and dark, linked to the demo."""
        sources = {}
        for theme in ("light", "dark"):
            image = Image.open(io.BytesIO(fetch(shot[theme]))).convert("RGB")
            srcset = []
            for width in SHOT_WIDTHS:
                height = round(image.height * width / image.width)
                name = f"img/report-{theme}-{width}.webp"
                image.resize((width, height), Image.LANCZOS).save(self.out / name, "WEBP", quality=80, method=6)
                srcset.append(f"/{name} {width}w")
            sources[theme] = ", ".join(srcset)
            size = (image.width, image.height)
        sizes = "(max-width: 52rem) calc(100vw - 4rem), 38rem"
        return (
            f'<a class="shot" href="{esc(link)}"><picture><source media="(prefers-color-scheme: dark)" srcset="{sources["dark"]}" sizes="{sizes}">'
            f'<img src="/img/report-light-{SHOT_WIDTHS[0]}.webp" srcset="{sources["light"]}" sizes="{sizes}" '
            f'width="{size[0]}" height="{size[1]}" alt="{esc(shot["alt"])}" decoding="async"></picture></a>'
            f"<figcaption>{esc(shot['caption'])}</figcaption>"
        )

    def flagship(self) -> str:
        f = self.config["flagship"]
        points = "".join(f"<li><b>{esc(p['title'])}</b> {esc(p['text'])}</li>" for p in f["points"])
        links = "".join(
            f'<a class="btn{" primary" if link.get("primary") else ""}" href="{esc(link["url"])}">{esc(link["label"])}</a>'
            for link in f["links"]
        )
        packages = "".join(f"<li>{esc(p)}</li>" for p in f["packages"])
        version = shields_value(f["badge"])
        kicker = f["kicker"] + (f" · {version}" if version else "")
        return f"""  <section class="wrap" id="{esc(f["name"])}" aria-labelledby="flagship-title">
    <div class="flag">
      <div class="flag-head">{self.brand_svg(f["icon"])}<div><div class="kicker">{esc(kicker)}</div><h2 id="flagship-title"><a href="{github_url(f["repo"])}">{esc(f["name"])}</a></h2></div></div>
      <p class="lead">{esc(f["lead"])}</p>
      <div class="flag-grid">
        <div class="flag-text">
          <ul class="points">{points}</ul>
          <div class="actions">{links}</div>
          <code class="install">{esc(f["install"])}</code>
          <div><p class="pkgs-label">{esc(f["packages_label"])}</p><ul class="pkgs">{packages}</ul></div>
        </div>
        <figure>{self.screenshot(f["screenshot"], f["links"][0]["url"])}</figure>
      </div>
    </div>
  </section>"""

    def card(self, project: dict) -> str:
        meta = []
        for v in project.get("versions", []):
            value = shields_value(v["badge"])
            if value:
                meta.append(f"<span>{esc(v['label'])} <b>{esc(value)}</b></span>")
        if project.get("stars"):
            stars = shields_value(f"github/stars/{project['repo']}")
            if stars:
                meta.append(f"<span>{esc(stars)} stars</span>")
        if "downloads" in project:
            downloads = shields_value(project["downloads"])
            if downloads:
                meta.append(f"<span>{esc(downloads)} downloads</span>")
        meta += [f"<span>{esc(note)}</span>" for note in project.get("notes", [])]
        library = ""
        if lib := project.get("library"):
            version = shields_value(lib["badge"])
            library = (
                f'<div class="sub">Library: <a href="{esc(lib["url"])}">{esc(lib["name"])}</a>'
                + (f' <span class="mono">{esc(version)}</span>' if version else "")
                + f" on {registry_name(lib['badge'])}</div>"
            )
        links = (f'<a href="{esc(project["docs"])}">Docs</a>' if "docs" in project else "") + (
            f'<a href="{github_url(project["repo"])}">GitHub</a>'
        )
        return f"""      <article class="card">
        <div class="card-head">{self.icon(project)}<h3>{esc(project["name"])}</h3></div>
        <p>{esc(project["text"])}</p>
        <div class="meta">{"".join(meta)}</div>{library}
        <div class="links">{links}</div>
      </article>"""

    def groups(self) -> str:
        parts = []
        for group in self.config["groups"]:
            cards = "\n".join(self.card(p) for p in group["projects"])
            parts.append(
                f'    <section class="group dot-{esc(group["colour"])}">\n      <h2>{esc(group["title"])}</h2>\n'
                f'      <p>{esc(group["text"])}</p>\n      <div class="cards">\n{cards}\n      </div>\n    </section>'
            )
        return "\n".join(parts)

    def contributions(self) -> str:
        items = "".join(
            f'<p><a href="{github_url(c["repo"])}">{esc(c["name"])}</a>: {esc(c["text"])}</p>'
            for c in self.config.get("contributions", [])
        )
        return (
            f'  <section class="wrap contrib">\n    <h2>Contributions</h2>\n    {items}\n  </section>' if items else ""
        )

    def build(self) -> None:
        if self.out.exists():
            shutil.rmtree(self.out)
        (self.out / "img").mkdir(parents=True)
        for name, path in BRAND_FILES.items():
            (self.out / name).write_bytes(fetch(f"{self.brand}/{path}"))

        site = self.config["site"]
        style = (SITE / "style.css").read_text()
        style_hash = base64.b64encode(hashlib.sha256(style.encode()).digest()).decode()
        csp = (
            f"default-src 'none'; img-src 'self'; style-src 'sha256-{style_hash}'; "
            "manifest-src 'self'; base-uri 'none'; form-action 'none'"
        )
        mark = self.brand_svg("eizedev/svg/mark-on-light.svg", "on-light") + self.brand_svg(
            "eizedev/svg/mark-on-dark.svg", "on-dark"
        )
        intro = self.config["intro"]
        values = {
            "csp": csp,
            "style": style,
            "title": esc(site["title"]),
            "description": esc(site["description"]),
            "url": esc(site["url"]),
            "github": esc(site["github"]),
            "sponsor": esc(site["sponsor"]),
            "contact": esc(site["contact"]),
            "mark": mark,
            "prompt": esc(intro["prompt"]),
            "headline": esc(intro["headline"]),
            "intro": esc(intro["text"]),
            "social_alt": esc(site["social_alt"]),
            "json_ld": json_ld(self.config),
            "flagship_id": esc(self.config["flagship"]["name"]),
            "flagship_name": esc(self.config["flagship"]["name"]),
            "flagship": self.flagship(),
            "groups": self.groups(),
            "contributions": self.contributions(),
        }
        page = (SITE / "page.html").read_text()
        page = re.sub(r"\{\{(\w+)\}\}", lambda m: values[m.group(1)], page)
        (self.out / "index.html").write_text(page)
        (self.out / "robots.txt").write_text(f"User-agent: *\nAllow: /\n\nSitemap: {site['url']}/sitemap.xml\n")
        (self.out / "sitemap.xml").write_text(sitemap(site["url"]))
        (self.out / "llms.txt").write_text(llms_txt(self.config))
        size = sum(p.stat().st_size for p in self.out.rglob("*") if p.is_file())
        print(f"built {self.out} ({len(page.encode()) // 1024} KiB page, {size // 1024} KiB in total)")


# ----------------------------------------------------------------- for search engines and agents


def all_projects(config: dict) -> list[dict]:
    """The flagship and every project of every group, in page order."""
    return [config["flagship"]] + [p for g in config["groups"] for p in g["projects"]]


def project_url(project: dict) -> str:
    return project.get("docs") or github_url(project["repo"])


def sitemap(url: str) -> str:
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"  <url><loc>{esc(url)}/</loc></url>\n"
        "</urlset>\n"
    )


def llms_txt(config: dict) -> str:
    """eize.dev for language models (https://llmstxt.org): what is here and where the docs are."""
    site, f = config["site"], config["flagship"]
    lines = [
        f"# {site['title']}",
        "",
        f"> {site['description']}",
        "",
        f"{config['intro']['text']} Source code: {site['github']}. Contact: {site['contact']}.",
        "",
        "## Main project",
        "",
        f"- [{f['name']}]({f['docs']}): {f['lead']}",
    ]
    if "llms" in f:
        lines.append(f"- [{f['name']} documentation for language models]({f['llms']}): every page of the docs")
    for group in config["groups"]:
        lines += ["", f"## {group['title']}", ""]
        for p in group["projects"]:
            lines.append(f"- [{p['name']}]({project_url(p)}): {p['text']} Code: {github_url(p['repo'])}")
            if lib := p.get("library"):
                lines.append(f"- [{lib['name']}]({lib['url']}): the Python library behind {p['name']}.")
            if "llms" in p:
                lines.append(f"- [{p['name']} documentation for language models]({p['llms']})")
    if config.get("contributions"):
        lines += ["", "## Optional", ""]
        lines += [f"- [{c['name']}]({github_url(c['repo'])}): {c['text']}" for c in config["contributions"]]
    return "\n".join(lines) + "\n"


def json_ld(config: dict) -> str:
    """schema.org data for search engines: the person and the projects. A data block, never run,
    so the Content-Security-Policy (no scripts) does not affect it."""
    site = config["site"]
    person = {
        "@type": "Person",
        "@id": f"{site['url']}/#me",
        "name": site["author"],
        "alternateName": site["title"],
        "email": f"mailto:{site['contact']}",
        "url": f"{site['url']}/",
        "sameAs": [site["github"]],
    }
    projects = [
        {
            "@type": "SoftwareSourceCode",
            "name": p["name"],
            "description": p.get("lead") or p["text"],
            "url": project_url(p),
            "codeRepository": github_url(p["repo"]),
            "author": {"@id": person["@id"]},
        }
        for p in all_projects(config)
    ]
    data = {"@context": "https://schema.org", "@graph": [person, *projects]}
    # "</" must not appear inside a script element
    return json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")


# -------------------------------------------------------------------------------------- README


def readme_projects(config: dict) -> str:
    """The projects part of the profile README. Uses only projects.toml, so it needs no network."""
    brand = config["site"]["brand"]
    f = config["flagship"]
    first, _, rest = f["lead"].partition(". ")
    shot = f["screenshot"]
    lines = [
        f'## <img src="{brand}/{f["icon"]}" alt="" height="28" align="top"> [{f["name"]}]({github_url(f["repo"])})',
        "",
        f"**{first}.** {rest}",
        "",
        *[f"- **{p['title']}** {p['text']}" for p in f["points"]],
        "",
        " · ".join(f"[{link['label']}]({link['url']})" for link in f["links"])
        + f" · [![npm]({badge_image(f['badge'], BLUE, 'npm')})]({badge_link(f['badge'])})",
        "",
        f'<a href="{f["links"][0]["url"]}"><picture>',
        f'  <source media="(prefers-color-scheme: dark)" srcset="{shot["dark"]}">',
        f'  <img alt="{shot["alt"]}" src="{shot["light"]}" width="720">',
        "</picture></a>",
        "",
        "## More projects",
    ]
    for group in config["groups"]:
        lines += ["", f"### {group['title']}", "", "| Project | What it is |", "| :-- | :-- |"]
        for p in group["projects"]:
            icon = f'<img src="{brand}/{p["icon"]}" alt="" height="20" align="top"> ' if "icon" in p else ""
            badges = [
                f"[![{v['label']}]({badge_image(v['badge'], BLUE, v['label'] if len(p['versions']) > 1 else None)})]({badge_link(v['badge'])})"
                for v in p.get("versions", [])
            ]
            if "downloads" in p:
                badges.append(f"[![Downloads]({badge_image(p['downloads'], GREEN)})]({badge_link(p['downloads'])})")
            what = [p["text"]]
            if lib := p.get("library"):
                what.append(
                    f"Library: [{lib['name']}]({lib['url']}) [![{registry_name(lib['badge'])}]({badge_image(lib['badge'], BLUE)})]({badge_link(lib['badge'])})"
                )
            if "docs" in p:
                what.append(f"[Documentation]({p['docs']})")
            lines.append(
                f"| {icon}**[{p['name']}]({github_url(p['repo'])})**<br>{' '.join(badges)} | {'<br>'.join(what)} |"
            )
    if config.get("contributions"):
        lines += ["", "## Contributions", "", "| Project | My part |", "| :-- | :-- |"]
        for c in config["contributions"]:
            badge = (
                f"<br>[![Downloads]({badge_image(c['downloads'], GREEN)})]({badge_link(c['downloads'])})"
                if "downloads" in c
                else ""
            )
            lines.append(f"| **[{c['name']}]({github_url(c['repo'])})**{badge} | {c['text']} |")
    return "\n".join(lines)


def readme_with_projects(config: dict) -> str:
    text = README.read_text()
    start, end = text.index(README_START), text.index(README_END)
    return text[: start + len(README_START)] + "\n" + readme_projects(config) + "\n" + text[end:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=ROOT / "_site", help="output folder of the page")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--readme", action="store_true", help="rewrite the projects part of README.md")
    group.add_argument("--check-readme", action="store_true", help="fail when README.md is out of date")
    args = parser.parse_args()
    config = tomllib.loads((ROOT / "projects.toml").read_text())

    if args.readme or args.check_readme:
        wanted = readme_with_projects(config)
        if args.readme:
            README.write_text(wanted)
            print("README.md updated")
        elif wanted != README.read_text():
            print("README.md does not match projects.toml: run `uv run site/build.py --readme`", file=sys.stderr)
            return 1
        return 0

    Page(config, args.out).build()
    return 0


if __name__ == "__main__":
    sys.exit(main())
